"""Generates lib/oui/MakersTable.inc from the IEEE MA-L registry (oui.csv).

Usage: python -I tools/oui/gen_makers.py build/oui.csv lib/oui/MakersTable.inc
Download the registry from https://standards-oui.ieee.org/oui/oui.csv first.
"""
import csv
import re
import sys

# Maker enum name -> regex on the registered organisation name. Order matters: first match wins.
MAKERS = [
    ("Axon", r"^Axon Enterprise"),
    ("Flock", r"^Flock Safety"),
    ("Ring", r"^Ring LLC"),
    ("Blink", r"^(Blink by Amazon|Immedia Semiconductor)"),
    ("Wyze", r"^Wyze Labs"),
    ("Arlo", r"^Arlo Technolog"),
    ("Eufy", r"(Anker Innovations|Fantasia Trading|Oceanwing)"),
    ("Hikvision", r"Hikvision"),
    ("Dahua", r"Dahua"),
    ("Reolink", r"Reolink"),
    ("Nest", r"^Nest Labs"),
    ("Tuya", r"^Tuya"),
    ("Apple", r"^Apple, Inc"),
    ("Samsung", r"^Samsung Electronics"),
    ("Google", r"^Google, Inc"),
    ("Amazon", r"^Amazon Technologies"),
    ("Microsoft", r"^Microsoft"),
    ("Intel", r"^Intel Corporate"),
    ("Motorola", r"^Motorola Mobility"),
    ("Huawei", r"^Huawei (Technologies|Device)"),
    ("Xiaomi", r"^(Xiaomi|Beijing Xiaomi)"),
    ("Oneplus", r"^OnePlus"),
    ("Lg", r"^LG Electronics"),
    ("Sony", r"^Sony"),
    ("Espressif", r"^Espressif"),
]


def main(src, dst):
    rows = []
    with open(src, encoding="utf-8", errors="replace") as f:
        for reg, assignment, org, *_ in csv.reader(f):
            if reg != "MA-L":
                continue
            for name, pattern in MAKERS:
                if re.search(pattern, org.strip(), re.I):
                    rows.append((int(assignment, 16), name))
                    break
    rows.sort()
    with open(dst, "w", encoding="utf-8") as f:
        f.write("// Generated by tools/oui/gen_makers.py from the IEEE MA-L registry. Do not edit.\n")
        for oui, name in rows:
            f.write("{0x%06X, Maker::%s},\n" % (oui, name))
    print("%d OUIs -> %s" % (len(rows), dst))


if __name__ == "__main__":
    main(sys.argv[1], sys.argv[2])
